export type DeckGlyph = 'code' | 'braces' | 'prompt' | 'cards' | 'layout' | 'components' | 'db' | 'branch' | 'globe' | 'cube' | 'tree' | 'shield' | 'stack';

export interface FlashCard {
  id: string;
  q: string;
  a: string;
}

export interface Deck {
  id: string;
  title: string;
  desc: string;
  glyph: DeckGlyph;
  /** Two colours for the deck gradient */
  tint: [string, string];
  cards: FlashCard[];
  builtin?: boolean;
}

const mk = (prefix: string, rows: [string, string][]): FlashCard[] => rows.map(([q, a], i) => ({ id: `${prefix}${i + 1}`, q, a }));

